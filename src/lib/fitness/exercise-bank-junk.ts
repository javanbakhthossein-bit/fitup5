/** الگوهای نام‌سازی («با مکس»، «بامکس» و مشابه — دیرکتیو مالک) */
export const JUNK_NAME_PATTERNS: RegExp[] = [/\bبامکس\b/u, /با\s*مکس\b/u];

const JUNK_EXACT = new Set([...JUNK_EXERCISE_NAMES, ...DUPLICATE_EXERCISE_NAMES]);

/** آیا این نام حرکت، از حرکات الکی/تکراری حذف‌شده است؟ (تطبیق دقیق + الگو) */
export function isJunkExerciseName(name: string): boolean {
  const trimmed = (name ?? "").trim();
  if (!trimmed) return false;
  if (JUNK_EXACT.has(trimmed)) return true;
  return JUNK_NAME_PATTERNS.some((r) => r.test(trimmed));
}
