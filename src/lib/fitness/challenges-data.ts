/**
 * پیشرفت هفتگی: هفته ۱-۲ پایه، هفته ۳ تکرارها +۲، هفته ۴+ تکرارها +۴
 * (برای «30s» زمان +10s در هفته ۳ و +20s در هفته ۴+)
 */
function progressedReps(reps: string, week: number): string {
  if (week < 3) return reps;
  const isTime = reps.trim().toLowerCase().endsWith("s");
  const add = week === 3 ? (isTime ? 10 : 2) : isTime ? 20 : 4;
  const m = reps.match(/(\d+)\s*-\s*(\d+)/);
  if (isTime) {
    const base = parseInt(reps, 10) || 30;
    return `${base + add}s`;
  }
  if (m) return `${Number(m[1]) + add}-${Number(m[2]) + add}`;
  const single = parseInt(reps, 10);
  if (!Number.isNaN(single)) return `${single + add}`;
  return reps;
}

export function buildChallengeDay(ch: ChallengeDef, dayNumber: number): BuiltChallengeDay {
  const total = Math.max(1, ch.durationDays);
  const day = Math.min(Math.max(1, Math.round(dayNumber)), total);
  const week = Math.ceil(day / 7);
  const tpl = ch.dayTemplates[(day - 1) % ch.dayTemplates.length];
  const exercises: BuiltChallengeExercise[] = tpl.exercises.map((spec, i) => {
    const info = chExInfo(spec.name);
    const reps = progressedReps(spec.reps, week);
    return {
      id: `${ch.slug}-d${day}-${i}`,
      name: spec.name,
      muscle: spec.muscle,
      category: "challenge",
      description: info.d,
      tips: info.t,
      mediaUrl: "",
      difficulty: CH_DIFFICULTY_LABELS[ch.difficulty],
      animKey: spec.animKey,
      sets: Array.from({ length: spec.sets }, (_, s) => ({
        setNumber: s + 1,
        reps,
        restSec: spec.restSec,
      })),
    };
  });
  return {
    dayNumber: day,
    week,
    title: `روز ${day} از ${total}`,
    focus: tpl.focus,
    templateTitle: tpl.title,
    exercises,
    estimatedMinutes: ch.minutesPerDay,
  };
}

