export type ChallengeGender = "men" | "women";
export type ChallengeDifficulty = "beginner" | "intermediate" | "advanced";

/** مشخصات یک حرکت داخل قالب روز چالش */
export interface ChallengeExerciseSpec {
  /** نام فارسی — دقیقاً با سبک بانک حرکات («نام فارسی (English)») تا ویدیو تطبیق بخورد */
  name: string;
  /** عضلهٔ هدف — فارسی */
  muscle: string;
  /** تعداد ست */
  sets: number;
  /** هدف تکرار — «12-15» یا «30s» (نمایش فارسی در رندر) */
  reps: string;
  /** استراحت بعد از هر ست (ثانیه) */
  restSec: number;
  /** کلید انیمیشن دوفریمی — /animations/challenges/<animKey>-0.webp و -1.webp */
  animKey?: string;
}

/** یک قالب روز تمرین (چرخهٔ هفتگی — روزها روی قالب‌ها می‌چرخند + پیشرفت هفتگی) */
export interface ChallengeDayTemplate {
  /** عنوان روز — «بالاتنه و مرکز بدن» */
  title: string;
  /** فوکوس کوتاه */
  focus: string;
  exercises: ChallengeExerciseSpec[];
}

export interface ChallengeDef {
  /** شناسه یکتا (پیشوند m-/w-) — کلید پیشرفت در DB */
  slug: string;
  gender: ChallengeGender;
  /** عنوان جذاب کارت */
  title: string;
  /** یک خط هیجان‌انگیز زیر عنوان */
  tagline: string;
  /** توضیح ۲-۳ جمله‌ای صفحهٔ جزئیات */
  description: string;
  /** رشتهٔ مرتبط (برچسب چیپ) */
  disciplineLabel: string;
  difficulty: ChallengeDifficulty;
  durationDays: number;
  /** روز تمرین در هفته */
  daysPerWeek: number;
  /** دقیقهٔ تقریبی هر جلسه */
  minutesPerDay: number;
  /** تجهیزات لازم — فارسی */
  equipment: string;
  /** مسیر عکس کارت — /images/challenges/<gender>/<slug>.jpg */
  cover: string;
  /** گرادیان اختصاصی کارت (from → via → to با کلاس‌های tailwind نمی‌سازیم؛ استایل inline) */
  accent: { from: string; via: string; to: string };
  emoji: string;
  /** قالب‌های روز (چرخهٔ ۲ تا ۴ روزه) */
  dayTemplates: ChallengeDayTemplate[];
}

/** روزِ ساخته‌شدهٔ مشخص یک چالش (خروجی buildChallengeDay) */
export interface BuiltChallengeDay {
  dayNumber: number;
  week: number;
  title: string;
  focus: string;
  templateTitle: string;
  exercises: BuiltChallengeExercise[];
  estimatedMinutes: number;
}

/** حرکتِ ساخته‌شدهٔ روز — با ست‌های کامل (سازگار با ساختار PlanExercise پنل) */
export interface BuiltChallengeExercise {
  id: string;
  name: string;
  muscle: string;
  category: string;
  description: string;
  tips: string;
  mediaUrl: string;
  difficulty: string;
  animKey?: string;
  sets: Array<{ setNumber: number; reps: string; restSec: number }>;
}

