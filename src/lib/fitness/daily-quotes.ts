/* ─────────────────── تبدیل تاریخ شمسی (بدون وابستگی خارجی) ─────────────────── */

/** تبدیل میلادی → جلالی */
function toJalali(d: Date): { jy: number; jm: number; jd: number } {
  try {
    // مسیر استاندارد Intl (سریع و دقیق — در همه‌ی محیط‌های Node مدرن موجود است)
    const fmt = new Intl.DateTimeFormat("en-u-ca-persian", {
      year: "numeric",
      month: "numeric",
      day: "numeric",
      timeZone: "Asia/Tehran",
    });
    const parts = fmt.formatToParts(d);
    const get = (t: string) => Number(parts.find((p) => p.type === t)?.value ?? 0);
    return { jy: get("year"), jm: get("month"), jd: get("day") };
  } catch {
    // fallback تقویم جلالی (بیدا/رشیدیه ساده‌شده)
    const gy = d.getFullYear();
    const doy = Math.floor((d.getTime() - new Date(gy, 2, 21).getTime()) / 86400000);
    const jml = [31, 31, 31, 31, 31, 31, 30, 30, 30, 30, 30, 29];
    let jm = 1;
    let rem = doy;
    while (jm < 12 && rem >= jml[jm - 1]) {
      rem -= jml[jm - 1];
      jm += 1;
    }
    return { jy: gy - 621, jm, jd: rem + 1 };
  }
}

/** روزِ سال شمسی (۰..۳۶۵) */
function persianDayOfYear(): number {
  const { jm, jd } = toJalali(new Date());
  const jml = [31, 31, 31, 31, 31, 31, 30, 30, 30, 30, 30, 29];
  let doy = jd;
  for (let i = 0; i < jm - 1; i++) doy += jml[i];
  return doy - 1;
}

/** تاریخ شمسیِ خوانا برای نمایش کنار جمله */
export function persianDateString(): string {
  const { jy, jm, jd } = toJalali(new Date());
  const MONTHS = [
    "فروردین", "اردیبهشت", "خرداد", "تیر", "مرداد", "شهریور",
    "مهر", "آبان", "آذر", "دی", "بهمن", "اسفند",
  ];
  return `${toPersianDigits(jd)} ${MONTHS[jm - 1]} ${toPersianDigits(jy)}`;
}

function toPersianDigits(n: number): string {
  return String(n).replace(/\d/g, (x) => "۰۱۲۳۴۵۶۷۸۹"[Number(x)]);
}

export interface DailyQuote {
  text: string;
  author: string;
  index: number;
  total: number;
  dateKey: string;
}

/** جمله‌ی انگیزشیِ امروز — قطعی و پایدار برای هر کاربر در همان روز (بدون API) */
export function getDailyQuote(): DailyQuote {
  const doy = persianDayOfYear();
  const index = doy % GREAT_QUOTES.length;
  const q = GREAT_QUOTES[index];
  return {
    text: q.text,
    author: q.author,
    index,
    total: GREAT_QUOTES.length,
    dateKey: persianDateString(),
  };
}
