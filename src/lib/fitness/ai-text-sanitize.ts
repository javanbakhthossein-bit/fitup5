/**
 * ═══════════════════════════════════════════════════════════════════════
 *  v159 — پاک‌ساز متن تحلیل AI (T6 — گزارش مالک: «یک عالمه از این‌ها است \n-»)
 * ═══════════════════════════════════════════════════════════════════════
 *
 * مدل‌های زبانی گاهی در خروجیِ رشتهٔ JSON خود، به‌جای خط واقعی، دنبالهٔ
 * فرار «\n-» (بک‌اسلاین + n + خط‌تیره) تولید/ذخیره می‌کنند و متن کاربر
 * پر از «\n-» و بولت‌های خراب می‌شود. این پاک‌ساز هم سمت سرور (قبل از
 * ذخیره) و هم سمت کلاینت (رندر دفاعیِ رکوردهای قدیمی) صدا زده می‌شود:
 *  ۱) «\n» لفظی (بک‌اسلاین-n) و «\\n» → خط واقعی
 *  ۲) «\r» لفظی/واقعی → حذف (نیاز نداریم)
 *  ۳) بولت‌های خراب «\n-» / « -  » وسط جمله → بولت تمیز «•  » یا خط واقعی
 *  ۴) خط خالی بیش‌ازحد → حداکثر یکی
 *  ۵) فاصله‌های ابتدایی/انتهایی حذف
 */

/** پاک‌سازی متن تحلیل AI — خروجی همیشه قابل‌نمایش است (هرگز JSON dump نیست) */
export function sanitizeAiText(input: string | null | undefined): string {
  if (!input || typeof input !== "string") return "";
  let text = input;

  // ۱) دنباله‌های فرار لفظی: \\n و \n (بک‌اسلاین+n واقعی در رشته) → خط واقعی
  //    (\\r\\n و \\t هم پوشش داده می‌شود)
  text = text
    .replace(/\\r\\n/g, "\n")
    .replace(/\\n/g, "\n")
    .replace(/\\r/g, "")
    .replace(/\\t/g, "  ");

  // حذف CR واقعی
  text = text.replace(/\r/g, "");

  // ۲) بولت‌های خراب: خط‌تیرهٔ آغازین بعد از خط جدید → بولت تمیز
  //    (الماس تیرهٔ یونیکد جایگزین «-» معیوب؛ بدون تغییر خط‌های واقعی سالم)
  text = text.replace(/(^|\n)\s*[-–—*]\s+/g, (_m, p1) => `${p1}• `);

  // ۳) « - » معیوب وسط متن‌های یک‌خطی که مدل به‌جای خط جدید پاشیده:
  //    فاصله + خط‌تیره + فاصله بین دو جملهٔ فارسی → خط جدید + بولت
  //    (گارد: فقط وقتی قبل از خط‌تیره نقطه/؟/!/؛ یا کلمهٔ کوتاه و بعدش حروف فارسی است
  //     تا اعداد منفی/کلمات با خط‌تیره مثل «چربی‌سوزی-هوازی» خراب نشوند)
  text = text.replace(/([.!؟?؛;:…])\s*[-–—]\s+(?=[\u0600-\u06FF])/g, "$1\n• ");

  // ۴) خط خالی بیش‌ازحد → حداکثر یکی
  text = text.replace(/\n{3,}/g, "\n\n");

  // ۵) فاصله‌های انتهای خطوط + تrim
  text = text
    .split("\n")
    .map((l) => l.replace(/[ \t]+$/g, ""))
    .join("\n")
    .trim();

  return text;
}
