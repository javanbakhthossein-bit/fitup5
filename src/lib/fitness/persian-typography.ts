/**
 * ─── اصلاح تایپوگرافی فارسی متن‌های AI ───
 *
 * مشکل (گزارش مالک): در تحلیل آنبوردینگ بعضی کلمات بدون فاصله و چسبیده به
 * هم نمایش داده می‌شوند — مثلاً «کم‌وزنی» به‌صورت «کموزنی».
 *
 * علت: مدل‌های زبانی گاهی نیم‌فاصله (ZWNJ) را حذف می‌کنند یا کلمات مرکب
 * را می‌چسبانند. متن تولیدی در DB هم cache می‌شود، پس هم متن تازه و هم
 * متن کش‌شده باید در لحظه‌ی خواندن اصلاح شوند.
 *
 * راه‌حل: دیکشنری کلمات مرکب پرکاربرد حوزه‌ی تناسب‌اندام + قواعد عمومی
 * (پیشوندهای می/نمی/بی، پسوند «ها» و غیره) — بدون تغییر معنا.
 */

/** کلمات مرکب پرتکرار — جست‌وجو بدون حساسیت به نیم‌فاصله/فاصله */
const COMPOUND_WORDS: string[] = [
  // ─── v56: پسوندهای ملکی چسبیده (گزارش مالک: «برنامهات» به‌جای «برنامه‌ات») ───
  // بعد از مصوت (ا/ه/ی) ضمیر ملکی باید با نیم‌فاصله بنشیند —
  // این‌ها قبل از کلمات مرکب ساده می‌آیند تا نسخهٔ بلندتر اول جایگزین شود
  "برنامه‌ات", "برنامه‌ت", "برنامه‌تون", "برنامه‌ام",
  "زندگی‌ت", "زندگی‌ات", "زندگی‌تو", "زندگی‌تان",
  "ورزشی‌ت", "ورزشی‌تو", "ورزشی‌تان",
  "سهمیه‌ات", "سهمیه‌ت", "سهمیه‌تو",
  "غذایی‌ت", "غذایی‌تو", "تاریخچه‌ات", "تاریخچه‌ت",
  "پیگیری‌ات", "بدنسازی‌ات", "بدنسازی‌تو",
  "کم‌وزن", "اضافه‌وزن", "عضله‌سازی", "چربی‌سوزی", "برنامه‌ریزی",
  "بدن‌سازی", "وزن‌کشی", "کالری‌شمار", "قدرتی", "استقامتی",
  // ─── v59: کلمات چسبیدهٔ پرتکرار در پاسخ‌های نیکا (تست واقعی v59) ───
  // «بهطور کلی»، «بهعنوان»، «بصورت» (اصلاح املا هم‌زمان) و…
  "به‌طور", "به‌عنوان", "به‌صورت", "به‌ویژه", "به‌علاوه", "به‌خصوص", "به‌سرعت", "به‌دست", "به‌ترتیب", "به‌مرور", "به‌وجود", "به‌کار", "به‌شرط", "به‌عبارت", "به‌طور کلی", "به‌طور میانگین", "به‌طور کامل", "به‌صورت روزانه", "به‌صورت هفتگی", "به‌صورت علمی", "به‌صورت مستقیم", "به‌صورت کامل", "به‌صورت دقیق",
  // ⚠️ فقط کلماتی که فرم چسبیدهشان غلط است — «همچنین/همراه/همزمان» املای
  // درستِ پیوسته دارند و عمداً در لیست نیستند (تا متن درست خراب نشود).
  "مثلاً", "هم‌اکنون", "هم‌خوان", "هم‌دوره", "هم‌سطح", "هم‌وزن",
  "اوزان", "بدنساز", "حرکات", "کششی", "گشادی", "جذبی", "تنفسی",
  "اسکوات", "پرس", "ددلیفت", "دی‌پ", "اسکرینینگ",
];

/** نگاشت کلمهٔ درست (با نیم‌فاصله) — برای جست‌وجوی چسبیده */
const ZWNJ = "\u200c";

/**
 * v75-fix — کلاس «حروف فارسی/عربی» بدون علائم نگارشی — برای گارد مرز کلمه.
 * بازهٔ وسیع \u0600-\u06FF علائم «،؛؟.» را هم شامل می‌شود و کلمهٔ چسبیدهٔ
 * قبل از ویرگول («تمامقد،») را از تعمیر دور می‌کند — پس فقط حروف را می‌گیریم:
 * حروف عربی/فارسی اصلی (ء-غ، ف-ي) + چهار حرف مخصوص فارسی (پ چ ژ ک گ) + ی فارسی + تطویل.
 */
const FA_LETTER = "\\u0621-\\u063A\\u0641-\\u064A\\u067E\\u0686\\u0698\\u06A9\\u06AF\\u06CC\\u0640";

/**
 * اصلاح املای غلط رایج (v59) — صریح، مکانیزم joined این‌ها را پوشش نمی‌دهد
 * regex با گارد مرز کلمه تا داخل کلمهٔ دیگر رخنه نکند.
 */
const SPELLING_FIXES: Array<[RegExp, string]> = [
  [new RegExp(`(?<![${FA_LETTER}])بصورت(?![${FA_LETTER}])`, "g"), "به\u200cصورت"],
  [new RegExp(`(?<![${FA_LETTER}])مثلا(?![${FA_LETTER}])`, "g"), "مثلاً"],
];

/**
 * v75 — کلمات دوتایی‌ای که مدل به‌اشتباه چسبیده می‌نویسد و درستشان «با فاصله» است
 * (نه نیم‌فاصله!). گزارش واقعی مالک: «تمامقد» به‌جای «تمام قد» در چت با فیتاپ.
 * هر جفت با گارد مرز کلمهٔ فارسی اعمال می‌شود تا داخل کلمهٔ دیگر رخنه نکند
 * (مثلاً «تمامقدی» ساخته نمی‌شود). فقط امضاهای کاملاً شناخته‌شده — محافظه‌کارانه.
 */
const GLUED_SPACED_WORDS: Array<[string, string]> = [
  ["تمامقد", "تمام قد"],
  ["هربدنی", "هر بدنی"],
  ["درحالیکه", "در حالی‌که"],
  ["بااینحال", "با این حال"],
  ["بههرحال", "به هر حال"],
  ["ازطرفی", "از طرفی"],
  ["برایهمین", "برای همین"],
  ["برایمثال", "برای مثال"],
  ["باوجوداین", "با وجود این"],
  ["ازاینرو", "از این رو"],
];

/**
 * v76 — واژه‌های بیگانه/تخصصی که کاربر ایرانی کمتر می‌شنود (گزارش مالک:
 * «از گفتن کلماتی مثل پوسچر که کاربر ایرانی زیاد نشنیده پرهیز کن») —
 * هم در پاسخ‌های زندهٔ AI و هم در نمایش محتوای ذخیره‌شدهٔ قبلی با معادل
 * فارسیِ رایج جایگزین می‌شوند. با گارد مرز کلمهٔ فارسی.
 */
const FOREIGN_TERM_FIXES: Array<[RegExp, string]> = [
  // غلط املایی رایج مدل اول، بعد خود واژه
  [new RegExp(`(?<![${FA_LETTER}])پوستچر(?![${FA_LETTER}])`, "g"), "فرم بدن"],
  [new RegExp(`(?<![${FA_LETTER}])پوسچر(?![${FA_LETTER}])`, "g"), "فرم بدن"],
];

/** کلمهٔ بدون نیم‌فاصله → کلمهٔ با نیم‌فاصلهٔ درست */
function joinedVariant(word: string): string {
  return word.split(ZWNJ).join("");
}

/**
 * اصلاح متن فارسی:
 *  ۱) کلمات مرکب چسبیده → نیم‌فاصله‌دار («کموزنی» → «کم‌وزنی»)
 *  ۲) «می‌/نمی» چسبیده (میخواهی → می‌خواهی)
 *  ۳) فاصله‌های گم‌شده بعد از نقطه/ویرگول
 *  ۴) حذف فاصله‌های تکراری
 */
export function fixPersianTypography(input: string): string {
  if (!input) return input;
  let text = input;

  // ─── ۱) کلمات مرکب ───
  for (const word of COMPOUND_WORDS) {
    const joined = joinedVariant(word);
    if (!joined || joined === word) continue;
    // فقط وقتی چسبیده آمده عوض کن (نسخهٔ درست را دست نزن)
    const re = new RegExp(joined, "g");
    text = text.replace(re, word);
  }

  // ─── ۱-ب) اصلاح املای غلط رایج (v59 — تست واقعی نیکا) ───
  // مکانیزم بالا فقط ZWNJ را برمی‌گرداند (joined === word → رد می‌شود)؛
  // این نگاشت‌ها صریح‌اند: «بصورت» غلط است و باید «به‌صورت» شود.
  for (const [wrong, right] of SPELLING_FIXES) {
    text = text.replace(wrong, right);
  }

  // ─── ۱-ج) v75 — کلمات دوتایی چسبیده که درستشان «با فاصله» است ───
  // («تمامقد» → «تمام قد» — گزارش مالک). گارد مرز کلمهٔ فارسی دارد.
  for (const [joined, spaced] of GLUED_SPACED_WORDS) {
    text = text.replace(
      new RegExp(`(?<![${FA_LETTER}])${joined}(?![${FA_LETTER}])`, "g"),
      spaced
    );
  }

  // ─── ۱-د) v76 — جایگزینی واژه‌های بیگانه/تخصصی با معادل فارسی رایج ───
  // (گزارش مالک: «از گفتن کلماتی مثل پوسچر پرهیز کن») — روی متن‌های زندهٔ AI
  // و متن‌های ذخیره‌شدهٔ قبلی اعمال می‌شود؛ دیگر کاربر «پوسچر» نمی‌بیند.
  for (const [pattern, replacement] of FOREIGN_TERM_FIXES) {
    text = text.replace(pattern, replacement);
  }

  // ─── ۲) پیشوندهای می / نمی ───
  // v56: بازنویسی کامل — نسخهٔ قبلی فقط وقتی «ساقه» در انتهای کلمه بود می‌گرفت
  // (مثلاً «میخواهی» را نمی‌گرفت). حالا ساقه + ادامهٔ ارقام/حروف فارسی:
  // «میخواهی→می‌خواهی»، «میسازه→می‌سازه»، «میتونی→می‌تونی»، «نمیدم→نمی‌دم»...
  const MI_STEMS = "خواه|خو|خور|توان|تون|شو|شه|شن|شود|رود|ره|بایست|دون|گو|گه|بین|بینی|ساز|رس|گیر|پوش|ده|دی|بر|دار|دید|کن|کنی|کنه|شم|شینی|زن|ریز|سوز|چرب|سنج|پاش|کاه|انگیز";
  text = text.replace(
    new RegExp(`(^|[\\s\\u200c«»()\\[\\]:;،.؛!؟\\-])(نمی|می)((?:${MI_STEMS}))([\\u0600-\\u06FF\\u200c]*)`, "g"),
    (_m, p1: string, p2: string, p3: string, p4: string) => `${p1}${p2}${ZWNJ}${p3}${p4}`
  );

  // ─── ۳) فاصله بعد از نقطه و ویرگول ───
  // v75-fix — توالی نقطه (سه‌نقطه «...» یا «…») قبل از قاعده ماسک می‌شود وگرنه
  // قاعده، نقاط کنار هم را می‌شکند: «و...» → «و. ..». توالی اصلی برگردانده می‌شود.
  const elliMatches: string[] = [];
  text = text.replace(/(?:\u2026|\.{2,})/g, (m) => {
    elliMatches.push(m);
    return `\uE003${elliMatches.length - 1}\uE004`;
  });
  // v75-fix — کلاس رقم‌ها ارقام فارسی (۰-۹) و عربی (٠-٩) را هم شامل می‌شود تا
  // اعداد اعشاری فارسی («۲.۱») نشکنند؛ «۳۰۴۵. پروتئین» همچنان فاصله می‌گیرد.
  text = text.replace(/([،؛.!?؟])([^\s\d\u06F0-\u06F9\u0660-\u0669«»()])/g, "$1 $2");
  text = text.replace(/\uE003(\d+)\uE004/g, (_m, i) => elliMatches[Number(i)] ?? "");

  // ─── ۴) فاصله‌های تکراری ───
  text = text.replace(/[ \t]{2,}/g, " ");

  return text;
}

/**
 * نسخهٔ URL-safe برای متن‌های چتی (v59 — تست واقعی نیکا):
 * fixPersianTypography بعد از نقطه فاصله می‌گذارد و URL/دامنه را می‌شکند
 * («fittup.ir» → «fittup. ir»). این رپر لینک‌ها (URL خام، دامنه، لینک
 * مارک‌داون و اکشن) را موقتاً با placeholder ماسک می‌کند، متن فارسی را
 * اصلاح می‌کند و بعد لینک‌ها را دقیقاً سرِ جایشان برمی‌گرداند.
 */
const URL_MASK_RE =
  /\[([^\]]*)\]\(([^)\s]*)\)|https?:\/\/[^\s)«»\]]+|\b[a-zA-Z0-9-]+(?:\.[a-zA-Z0-9-]+)+\.[a-zA-Z]{2,6}(?:\/[^\s)«»\]]*)?|\b[a-zA-Z0-9-]+\.(?:ir|com|net|org|io|app|me)(?:\/[^\s)«»\]]*)?/g;

export function fixPersianTypographySafe(input: string): string {
  if (!input) return input;
  const tokens: string[] = [];
  const masked = input.replace(URL_MASK_RE, (m) => {
    tokens.push(m);
    // placeholder در ناحیهٔ Private Use — با هیچ قاعدهٔ فارسی تصادم ندارد
    return `\uE000${tokens.length - 1}\uE001`;
  });
  const fixed = fixPersianTypography(masked);
  return fixed.replace(/\uE000(\d+)\uE001/g, (_m, i) => tokens[Number(i)] ?? "");
}

/** حداقل طول رشته برای اعمال اصلاح — رشته‌های کوتاه (id، واحد، کلید) دست نمی‌خورند */
const MIN_FIX_LEN = 8;

/**
 * v75 — اصلاح تایپوگرافی روی کل آبجکت برنامه (تمرینی/غذایی/مکمل).
 *
 * چرا: متن برنامه‌ها قبلاً از فیلتر تایپوگرافی عبور نمی‌کرد و کلمات چسبیدهٔ
 * («تمامقد»، «بهصورت»، «میخواهی» و...) مستقیم در پنل کاربر و مدیر نمایش
 * داده می‌شدند. این تابع deep-walk می‌زند و فقط مقادیر string «متن‌مانند» را
 * اصلاح می‌کند:
 *  - رشته‌های کوتاه‌تر از ۸ کاراکتر (id، کد، واحد مثل «۳ عدد») دست‌نخورده
 *  - رشته‌های URL/base64/path دست‌نخورده (با fixPersianTypographySafe که لینک را ماسک می‌کند)
 *  - حروف انگلیسی خالص دست‌نخورده (اسامی حرکات مثل "Push Press" و کلیدها)
 * خروجی: همان آبجکت با متن‌های اصلاح‌شده (mutate درجا — برای جلوگیری از کپی بزرگ).
 */
export function fixPlanTypographyDeep<T>(value: T): T {
  if (typeof value === "string") {
    // فقط متن فارسی‌دار را اصلاح کن؛ انگلیسی خالص/عددی/URL بی‌مصرف است
    if (!/[\u0600-\u06FF]/.test(value)) return value;
    if (value.length < MIN_FIX_LEN) return value;
    if (/^(data:|https?:\/\/|\/|uploads\/)/i.test(value)) return value;
    return fixPersianTypographySafe(value) as unknown as T;
  }
  if (Array.isArray(value)) {
    for (let i = 0; i < value.length; i++) {
      value[i] = fixPlanTypographyDeep(value[i]);
    }
    return value;
  }
  if (value && typeof value === "object") {
    for (const key of Object.keys(value as Record<string, unknown>)) {
      (value as Record<string, unknown>)[key] = fixPlanTypographyDeep(
        (value as Record<string, unknown>)[key]
      );
    }
    return value;
  }
  return value;
}
