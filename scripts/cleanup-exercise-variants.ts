// ─── گام صفر (v116): گارد حفاظت برنامه‌های کاربران ───
// درخواست مالک: «اگر داخل برنامه‌ها حرکتی گفته باشه که الان پاک شده باشه چی؟
// من می‌خوام هر تمرینی که به یک ورزشکار داده می‌شه، اون حرکت و توضیحاتش وجود داشته باشه»
// → هر حرکتی که نامش در «هر» WorkoutPlan (برنامهٔ فعلی/تاریخچه) ارجاع شده باشد
//   هرگز حذف نمی‌شود — حتی اگر در فهرست حذف/الگوها باشد.

/** همهٔ واریانت‌های تطبیق یک نام (نرمال + بدون لاتین + هرکدام بدون «با») */
function protectionVariants(name: string): string[] {
  const norm = normalizeName(name);
  const noLatin = norm.replace(/[a-z0-9]+/g, "");
  const strip = (s: string) => s.replace(/با/g, "");
  return [...new Set([norm, strip(norm), noLatin, strip(noLatin)].filter(Boolean))];
}

async function loadReferencedExerciseKeys(): Promise<Set<string>> {
  const keys = new Set<string>();
  try {
    const plans = await db.workoutPlan.findMany({ select: { content: true } });
    for (const p of plans) {
      try {
        const data = JSON.parse(p.content);
        const days = Array.isArray(data?.days) ? data.days : [];
        for (const day of days) {
          const exercises = Array.isArray(day?.exercises) ? day.exercises : [];
          for (const ex of exercises) {
            const n = typeof ex?.name === "string" ? ex.name : "";
            if (!n) continue;
            for (const v of protectionVariants(n)) keys.add(v);
          }
        }
      } catch {
        // برنامهٔ خراب/ناقص — نادیده گرفته می‌شود
      }
    }
  } catch (e) {
    // اگر خواندن برنامه‌ها شکست خورد، گارد محتاطانه «همه‌چیز را حفظ می‌کند» —
    // یعنی در این اجرا فقط گزارش می‌دهیم و حذفی انجام نمی‌شود (امن‌ترین حالت).
    console.warn("⚠ خواندن برنامه‌های کاربران شکست خورد — گارد حفاظت کل بانک را نگه می‌دارد:", e instanceof Error ? e.message : e);
    keys.add("__ALL__");
  }
  return keys;
}

