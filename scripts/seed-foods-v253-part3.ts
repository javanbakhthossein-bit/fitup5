async function main() {
  // ---- Phase 1: add new foods (dedupe exact by name, internal + DB) ----
  const existingNames = (await db.foodLibrary.findMany({ select: { name: true } })).map((x) => x.name);
  const existing = new Set(existingNames);
  const data = cleaned.map(food).filter((x) => !existing.has(x.name));
  let added = 0;
  for (let i = 0; i < data.length; i += 80) {
    const res = await db.foodLibrary.createMany({ data: data.slice(i, i + 80) });
    added += res.count;
  }

  // ---- Phase 2: units enrichment — legacy rows with units=="" (LIMIT 300) ----
  const legacy = await db.foodLibrary.findMany({
    where: { units: "" },
    take: 300,
    orderBy: { createdAt: "asc" },
    select: { id: true, name: true, servingSize: true, servingGrams: true },
  });
  let unitsUpdated = 0;
  let sgSet = 0;
  for (const row of legacy) {
    const extra = unitsFor2(row.name);
    const units = wrap(extra ?? []); // else → [{"گرم",1}]
    const sg = row.servingGrams ?? gramsFromServing(row.servingSize);
    await db.foodLibrary.update({
      where: { id: row.id },
      data: { units, ...(sg !== null ? { servingGrams: sg } : {}) },
    });
    unitsUpdated++;
    if (sg !== null && row.servingGrams == null) sgSet++;
  }

  const total = await db.foodLibrary.count();
  const emptyUnits = await db.foodLibrary.count({ where: { units: "" } });
  console.log(`P1 script-rows=${cleaned.length} added=${added} dupes-skipped=${cleaned.length - data.length}`);
  console.log(`P2 legacy-scanned=${legacy.length} units-updated=${unitsUpdated} servingGrams-filled=${sgSet} (units-empty remaining=${emptyUnits})`);
  console.log(`FINAL TOTAL=${total}`);

  // verification samples
  const samples = ["کیک اسفنجی ساده", "چای سیاه شیرین", "بستنی لیوانی", "چیزبرگر", "خورش فسنجان اردک", "ماهی شیر کبابی", "کته برنج", "سس فلفل", "پودر قند", "باقالی‌پلو با ماهیچه"];
  for (const n of samples) {
    const hit = await db.foodLibrary.findFirst({
      where: { name: n },
      select: { name: true, calories: true, protein: true, carbs: true, fat: true, servingSize: true, units: true, servingGrams: true, source: true },
    });
    console.log(hit ? `OK ${hit.name} | ${hit.servingSize} | ${hit.calories}kcal P${hit.protein} C${hit.carbs} F${hit.fat} | sg=${hit.servingGrams} | src=${hit.source} | units=${(hit.units || "").slice(0, 110)}` : `MISSING ${n}`);
  }
}

