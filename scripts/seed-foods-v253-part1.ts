function food(r: Row) {
  const [name, category, kcal, p, c, f, serving, sg, vegan, units, source] = r;
  return {
    name,
    category,
    calories: Math.round(kcal),
    protein: p,
    carbs: c,
    fat: f,
    servingSize: serving,
    isVegan: vegan,
    units: JSON.stringify([{ label: "گرم", grams: 1 }, ...units.map(([label, grams]) => ({ label, grams }))]),
    servingGrams: sg,
    source: source ?? FA,
  };
}

async function main() {
  const existingNames = (await db.foodLibrary.findMany({ select: { name: true } })).map((x) => x.name);
  const existing = new Set(existingNames);
  const data = rows.map(food).filter((x) => !existing.has(x.name));
  let added = 0;
  for (let i = 0; i < data.length; i += 80) {
    const res = await db.foodLibrary.createMany({ data: data.slice(i, i + 80) });
    added += res.count;
  }
  const total = await db.foodLibrary.count();
  console.log(`before=${existingNames.length} rowsInScript=${rows.length} added=${added} TOTAL=${total}`);
  for (const n of ["گردو مغز", "شیر شکلاتی پروما کاله", "شیر پروتئینه پرو شیک کاله"]) {
    const hit = await db.foodLibrary.findFirst({
      where: { name: n },
      select: { name: true, calories: true, protein: true, carbs: true, fat: true, servingSize: true },
    });
    console.log(hit ? `OK ${hit.name} | ${hit.servingSize} | ${hit.calories} kcal P${hit.protein} C${hit.carbs} F${hit.fat}` : `MISSING ${n}`);
  }
}

main()
